let currentLanguage = "en";

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLanguage = lang;
  localStorage.setItem("tagExpressLang", lang);
  applyTranslations();
  updateMeta();
  updateLanguageButtons();
}

function applyTranslations() {
  const dict = translations[currentLanguage];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const text = getValueFromPath(dict, key);
    if (typeof text === "string") {
      el.textContent = text;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const text = getValueFromPath(dict, key);
    if (typeof text === "string") {
      el.setAttribute("placeholder", text);
    }
  });
}

function updateMeta() {
  const page = document.body.dataset.page;
  const metaInfo = translations[currentLanguage]?.meta?.[page];
  if (metaInfo) {
    document.title = metaInfo.title;
    const descTag = document.querySelector('meta[name="description"]');
    if (descTag) descTag.setAttribute("content", metaInfo.description);
  }
}

function updateLanguageButtons() {
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === currentLanguage);
  });
}

function getValueFromPath(obj, path) {
  return path.split(".").reduce((acc, key) => (acc ? acc[key] : undefined), obj);
}

(function initLanguage() {
  const saved = localStorage.getItem("tagExpressLang");
  currentLanguage = saved && translations[saved] ? saved : "en";
})();
